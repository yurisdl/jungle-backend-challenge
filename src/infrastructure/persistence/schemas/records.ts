import { EntitySchema } from '@mikro-orm/core';

/**
 * Persistence records. The domain classes stay free of ORM decorators;
 * these plain classes are mapped with `EntitySchema` and translated to and
 * from the domain through `rehydrate` factories (see mappers.ts).
 *
 * Money columns are `numeric(18,2)` mapped as `decimal` → JavaScript
 * string, so the exact decimal text travels from PostgreSQL to `Money`
 * without ever becoming a `number`.
 */
export class WalletRecord {
  id!: string;
  playerId!: string;
  currency!: string;
  balanceAmount!: string;
  version!: number;
  createdAt!: Date;
  updatedAt!: Date;
}

export const WalletSchema = new EntitySchema<WalletRecord>({
  class: WalletRecord,
  tableName: 'wallets',
  properties: {
    id: { type: 'uuid', primary: true },
    playerId: { type: 'uuid' },
    currency: { type: 'string', columnType: 'char(3)' },
    balanceAmount: { type: 'decimal', precision: 18, scale: 2 },
    version: { type: 'integer' },
    createdAt: { type: 'datetime', columnType: 'timestamptz' },
    updatedAt: { type: 'datetime', columnType: 'timestamptz' },
  },
});

